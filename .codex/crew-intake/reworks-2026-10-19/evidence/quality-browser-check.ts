async (page) => {
	const checks = [];
	const errors = [];
	const assert = (condition, message) => {
		if (!condition) throw new Error(message);
		checks.push(message);
	};
	page.on('pageerror', error => errors.push(error.message));
	page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
	try {
		await page.goto('http://localhost:4300/hub/projects');
		await page.getByRole('row', { name: 'Fixture Project 125', exact: true }).waitFor();
		assert(await page.getByRole('row').count() === 126, '125 Projects reachable without visible pagination');
		assert(await page.getByRole('treeitem', { name: 'Child folder', exact: true }).getAttribute('aria-level') === '2', 'Folder Tree retains nested level');
		await page.getByRole('button', { name: 'Fixture Customer', exact: true }).first().click();
		const customer = page.getByRole('dialog', { name: 'Fixture Customer', exact: true });
		await customer.waitFor();
		assert(!(await customer.textContent()).match(/conditions|adjustment|estimation/i), 'Customer Popover contains basic info only');
		assert(await customer.getByRole('button').count() === 0, 'Customer Popover exposes no actions');
		await page.keyboard.press('Escape');
		await page.getByRole('link', { name: 'Fixture Project 001', exact: true }).click();
		await page.getByRole('row', { name: 'Fixture Window 105', exact: true }).waitFor();
		assert(await page.getByRole('row').count() === 106, '105 Positions reachable without first-page truncation');
		assert(await page.getByText('Sort positions', { exact: true }).count() === 0, 'Separate Sort positions controller removed');
		await page.getByRole('button', { name: 'New Position', exact: true }).click();
		const position = page.getByRole('dialog', { name: 'New Position', exact: true });
		await position.waitFor();
		assert(await position.getByRole('combobox', { name: 'Profile System', exact: true }).isDisabled(), 'Profile System disabled until explicit Position Type');
		assert(await position.getByRole('combobox', { name: 'Subsystem', exact: true }).isDisabled(), 'Empty Subsystem remains visible and disabled');
		assert(await position.getByRole('combobox', { name: 'Rule Package', exact: true }).isDisabled(), 'Empty Rule Package remains visible and disabled');
		await position.getByRole('combobox', { name: 'Position Type', exact: true }).click();
		await page.getByRole('option', { name: 'Door / Window', exact: true }).click();
		await position.getByRole('spinbutton', { name: 'Number of fields in width', exact: true }).fill('2');
		await page.keyboard.press('Tab');
		await position.getByRole('spinbutton', { name: 'Partial width 2', exact: true }).waitFor();
		assert(await position.getByRole('spinbutton', { name: 'Partial width 1', exact: true }).inputValue() === '600', 'Auto distributes total width into displayed computed fields');
		await position.getByRole('switch', { name: 'Auto partial width 1', exact: true }).click();
		await position.getByRole('spinbutton', { name: 'Partial width 1', exact: true }).fill('400');
		await page.keyboard.press('Tab');
		assert(await position.getByRole('spinbutton', { name: 'Partial width 2', exact: true }).inputValue() === '800', 'Manual width updates remaining Auto value in place');
		const size = await position.evaluate(el => ({ client: el.clientWidth, scroll: el.scrollWidth }));
		assert(size.scroll <= size.client + 1, 'Two-column Position Dialog has no horizontal overflow');
		await page.screenshot({ path: 'quality-position.png' });
		await position.getByRole('button', { name: 'Cancel', exact: true }).click();
		await page.goto('http://localhost:4300/hub/printouts?inputType=PROJECT&inputId=10000000-0000-4000-8000-000000000003');
		await page.getByRole('checkbox', { name: 'Isolated Nine Controls', exact: true }).waitFor();
		assert(await page.getByRole('checkbox', { name: 'Planned Fixture', exact: true }).isDisabled(), 'Null-endpoint printout stays disabled');
		await page.getByRole('checkbox', { name: 'Isolated Nine Controls', exact: true }).check();
		await page.getByRole('button', { name: 'Continue to elements', exact: true }).click();
		await page.getByRole('row').filter({ hasText: 'Fixture Window 105' }).waitFor();
		assert(await page.locator('tbody tr').count() === 105, 'Physical Element step renders all 105 context Elements');
		await page.getByRole('button', { name: 'Continue to options', exact: true }).click();
		const review = page.getByRole('button', { name: 'Review printouts', exact: true });
		assert(await review.isDisabled(), 'Review is gated until an output format is selected');
		await page.getByRole('button', { name: 'PDF', exact: true }).click();
		const date = page.getByLabel(/^Fixture date/);
		await date.click();
		await date.press('ControlOrMeta+A');
		await date.pressSequentially('03/15/2025');
		await page.keyboard.press('Tab');
		assert(await review.isEnabled(), 'Valid typed date commits to the schema-owned option draft');
		await date.click();
		await date.press('ControlOrMeta+A');
		await date.pressSequentially('02/30/2025');
		await page.keyboard.press('Tab');
		assert(await review.isDisabled(), 'Impossible typed date blocks readiness');
		await date.click();
		await date.press('ControlOrMeta+A');
		await date.pressSequentially('03/15/2025');
		await page.keyboard.press('Tab');
		await page.getByRole('textbox', { name: /^Fixture text/ }).fill('');
		assert(await review.isDisabled(), 'Schema minLength error blocks Review');
		await page.getByRole('textbox', { name: /^Fixture text/ }).fill('Reviewer retained draft');
		await page.screenshot({ path: 'quality-printouts.png' });
		await review.click();
		assert(await page.locator('pl-status').filter({ hasText: 'PDF' }).count() === 1, 'Review displays a compact format Tag');
		await page.getByRole('button', { name: 'Edit', exact: true }).click();
		assert(await page.getByRole('textbox', { name: /^Fixture text/ }).inputValue() === 'Reviewer retained draft', 'Review/Edit preserves report option draft');
		assert(await date.inputValue() === '03/15/2025', 'Review/Edit preserves manually typed date');
		assert(await page.locator('select, dialog').count() === 0, 'No native Select/Dialog remains in rendered workflow');
		await page.goto('http://localhost:4300/hub/projects');
		await page.getByRole('button', { name: 'New Folder', exact: true }).first().click();
		const folder = page.getByRole('dialog', { name: 'Folder', exact: true });
		await folder.waitFor();
		assert(await folder.getByRole('textbox', { name: 'Folder name', exact: true }).isVisible(), 'New Folder uses anchored Popover form');
		await folder.getByRole('button', { name: 'Cancel', exact: true }).click();
		await page.getByRole('link', { name: 'Fixture Project 001', exact: true }).click();
		await page.getByRole('row', { name: 'Fixture Window 001', exact: true }).click();
		await page.getByRole('tab', { name: 'Elements', exact: true }).click();
		await page.getByRole('button', { name: 'Edit element', exact: true }).click();
		const element = page.getByRole('dialog', { name: 'Edit Element', exact: true });
		await element.waitFor();
		assert(await element.getByRole('textbox', { name: 'Description', exact: true }).inputValue() === 'Fixture instance', 'Element edit opens populated version-owned Popover');
		await element.getByRole('textbox', { name: 'Description', exact: true }).fill('Unsaved reviewer draft');
		await element.getByRole('button', { name: 'Cancel', exact: true }).click();
		await element.waitFor({ state: 'hidden' });
		assert(!await element.isVisible(), 'Element Popover cancels without persistence');
		const requests = await page.evaluate(() => window.fixtureRequests());
		assert(!requests.some(request => ['POST', 'PATCH', 'PUT', 'DELETE'].includes(request.method)), 'All reviewer navigation and cancellation checks caused zero mutation requests');
		assert(errors.length === 0, 'Browser raised no page exceptions');
		return { passed: true, checks, errors, scope: 'Independent current-source isolated browser fixture; no production generator or data writes.' };
	} catch (error) {
		return { passed: false, checks, errors, failure: error.message, url: page.url() };
	}
}
