async (page) => {
	const checks = [];
	const writes = [];
	const errors = [];
	const onError = (error) => errors.push(error.message);
	page.on('pageerror', onError);
	const listener = (request) => { if (request.url().includes(':3000/v1/') && !['GET', 'HEAD', 'OPTIONS'].includes(request.method())) writes.push({ method: request.method(), path: new URL(request.url()).pathname }); };
	page.on('request', listener);
	const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
	try {
		await page.getByRole('row', { name: 'Batch 125', exact: true }).waitFor();
		assert(await page.getByRole('row').count() === 126, 'All 125 Batches rendered across bounded transport pages');
		await page.getByRole('row', { name: 'Batch 001', exact: true }).getByRole('cell', { name: 'Fixture coordinator', exact: true }).click();
		await page.getByRole('heading', { name: 'Batch 001', exact: true }).waitFor();
		assert(new URL(page.url()).pathname === '/hub/fabrication-batches', 'Row click selects details without opening inner route');
		assert(await page.getByRole('tab', { name: 'Elements', exact: true }).count() === 0, 'List property panel contains no Elements tab');
		await page.getByRole('button', { name: 'Archive batch', exact: true }).click();
		const archive = page.getByRole('alertdialog').filter({ hasText: 'Archive Batch 001?' });
		await archive.waitFor();
		assert(writes.length === 0, 'Archive ConfirmPopup precedes mutation');
		await archive.getByRole('button', { name: 'Cancel', exact: true }).click();
		assert(writes.length === 0, 'Archive cancellation performs no write');
		await page.getByRole('button', { name: 'Archive batch', exact: true }).click();
		await archive.waitFor();
		await page.keyboard.press('Escape');
		await archive.waitFor({ state: 'hidden' });
		assert(writes.length === 0, 'Escape dismisses destructive popup without mutation');
		await page.getByRole('link', { name: 'Batch 001', exact: true }).click();
		await page.waitForURL('**/hub/fabrication-batches/batch-1');
		await page.getByRole('row', { name: 'Window 105', exact: true }).waitFor();
		assert(await page.getByRole('row').count() === 106, 'Name opens inner route with all 105 physical Elements');
		assert(await page.getByLabel('Breadcrumb', { exact: true }).textContent().then((text) => text.includes('FB-001') && text.includes('Batch 001')), 'Breadcrumb resolves actual batch identity');
		await page.getByRole('row', { name: 'Window 1', exact: true }).getByRole('cell', { name: 'Level 1', exact: true }).click();
		await page.getByRole('heading', { name: 'EL-001', exact: true }).waitFor();
		await page.screenshot({ path: 'fabrication-inner.png' });
		await page.getByRole('button', { name: 'Remove from batch', exact: true }).click();
		const removal = page.getByRole('alertdialog').filter({ hasText: 'Remove EL-001 from Batch 001?' });
		await removal.waitFor();
		await removal.getByRole('button', { name: 'Cancel', exact: true }).click();
		assert(writes.length === 0, 'Unassignment cancellation preserves membership');
		await page.getByRole('button', { name: 'Remove from batch', exact: true }).click();
		await removal.waitFor();
		await removal.getByRole('button', { name: 'Confirm', exact: true }).click();
		await page.getByRole('row', { name: 'Window 1', exact: true }).waitFor({ state: 'detached' });
		assert(writes.length === 1 && writes[0].method === 'DELETE' && writes[0].path.endsWith('/assignments/element-1'), 'Confirmed removal writes only selected physical membership');
		await page.getByRole('button', { name: 'Add project elements', exact: true }).click();
		const assignment = page.getByRole('dialog', { name: 'Add project elements', exact: true });
		await assignment.waitFor();
		const sizes = await assignment.evaluate((element) => ({ width: element.clientWidth, scroll: element.scrollWidth }));
		assert(sizes.scroll <= sizes.width + 1, 'Assignment Dialog has no horizontal overflow');
		await assignment.getByRole('combobox', { name: 'Project', exact: true }).click();
		await page.getByRole('option', { name: 'PR-001 · Fixture Project', exact: true }).click();
		await assignment.getByRole('button', { name: 'Add elements', exact: true }).click();
		const confirmation = page.getByRole('alertdialog').filter({ hasText: 'Only active, included, unassigned elements are added. Future elements are not added automatically.' });
		await confirmation.waitFor();
		assert(writes.length === 1, 'Batch assignment uses separate ConfirmDialog before write');
		await confirmation.getByRole('button', { name: 'Confirm', exact: true }).click();
		await page.getByText('0 elements added; 1 skipped because they were unavailable, excluded, or already assigned.', { exact: true }).waitFor();
		await assignment.waitFor({ state: 'hidden' });
		checks.push('Successful assignment closes its Dialog after the mutation');
		assert(writes.length === 2 && writes[1].method === 'POST' && writes[1].path.endsWith('/assignments'), 'Confirmed project assignment reports assigned/skipped outcomes');
		assert(await page.locator('select, dialog').count() === 0, 'Fabrication uses shared PrimeNG Select/Dialog instead of native counterparts');
		assert(errors.length === 0, 'No browser exceptions during confirmation, mutation, and navigation flows');
		return { checks, writes, errors, url: page.url(), note: 'Isolated browser fixture, no actual app data or backend requests.' };
	} finally { page.off('request', listener); page.off('pageerror', onError); }
}
